'use client';

import { useState, useEffect, useCallback } from 'react';
import { FileText, Download, RefreshCw } from 'lucide-react';
import { useAuth } from '@/contexts/AuthContext';
import { PageHeader, Button, Select, ErrorState, Card, Stagger, RevealItem } from '@/components/ui';
import { fetchStores } from '@/lib/api';
import { PRODUCT_NAME } from '@/lib/brand';
import { Store } from '@/types';
import {
  ReportKpiCards, ReportTrendPanel, ReportCategoryPanel, ReportTopItemsPanel, ReportStoreTable,
  SalesReport, ReportRange, REPORT_RANGE_DAYS,
} from '@/components/reports';

const RANGE_LABEL: Record<ReportRange, string> = { '7d': 'Last 7 Days', '30d': 'Last 30 Days', '90d': 'Last 90 Days' };

export default function ReportsPage() {
  const { authFetch } = useAuth();
  const [range, setRange] = useState<ReportRange>('7d');
  const [storeId, setStoreId] = useState<number | null>(null);
  const [stores, setStores] = useState<Store[]>([]);
  const [report, setReport] = useState<SalesReport | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(false);
  const [exporting, setExporting] = useState(false);

  useEffect(() => {
    fetchStores().then(setStores).catch(() => setStores([]));
  }, []);

  const loadReport = useCallback(async () => {
    setLoading(true);
    setError(false);
    try {
      const params = new URLSearchParams({ days: String(REPORT_RANGE_DAYS[range]) });
      if (storeId) params.append('store_id', String(storeId));
      const res = await authFetch(`/api/reports/sales?${params}`);
      if (res.ok) setReport(await res.json());
      else { setReport(null); setError(true); }
    } catch (err) {
      console.error('Failed to load report:', err);
      setReport(null);
      setError(true);
    } finally {
      setLoading(false);
    }
  }, [authFetch, range, storeId]);

  useEffect(() => {
    loadReport();
  }, [loadReport]);

  const handleExport = async () => {
    if (!report) return;
    setExporting(true);
    try {
      // Print-quality HTML export (E4-5) — browser print dialog → "Save as PDF".
      // Replaces the retired client-side jsPDF pipeline.
      const { printReport } = await import('@/lib/printExport');
      await printReport({
        title: 'Sales & Performance Report',
        subtitle: `${PRODUCT_NAME} — figures are units (synthetic demand data)`,
        dateRange: `Period: ${RANGE_LABEL[range]}${storeId ? ` · ${stores.find((s) => s.id === storeId)?.name ?? `Store ${storeId}`}` : ' · All stores'}`,
        kpis: [
          { label: 'Units Sold', value: report.kpis.total_sales.toLocaleString(), change: `${report.kpis.sales_growth >= 0 ? '+' : ''}${report.kpis.sales_growth.toFixed(1)}%` },
          { label: 'Transactions', value: report.kpis.total_transactions.toLocaleString() },
          { label: 'Avg Basket (units)', value: report.kpis.avg_basket_size.toFixed(1) },
        ],
        tables: [
          {
            title: 'Daily Volume',
            data: {
              headers: ['Date', 'Units', 'Transactions'],
              rows: report.daily_sales.map((d) => [d.date, d.sales.toLocaleString(), d.transactions.toLocaleString()]),
            },
          },
          {
            title: 'Units by Category',
            data: {
              headers: ['Category', 'Units', 'Share'],
              rows: report.category_breakdown.map((c) => [c.category, c.sales.toLocaleString(), `${c.percentage}%`]),
            },
          },
          {
            title: 'Store Performance',
            data: {
              headers: ['Store', 'Location', 'Units', 'Transactions'],
              rows: report.store_performance.map((s) => [s.store_name, s.location, s.sales.toLocaleString(), s.transactions.toLocaleString()]),
            },
          },
        ],
        footer: `Figures are units sold (Kaggle demand dataset has no price column). Generated by ${PRODUCT_NAME}.`,
      });
    } catch (err) {
      console.error('PDF export failed:', err);
    } finally {
      setExporting(false);
    }
  };

  return (
    <main className="min-h-screen p-4 md:p-8">
      <div className="max-w-7xl mx-auto">
        <PageHeader
          title="Sales Reports"
          description="Period sales reporting by category, store, and item — figures are units"
          icon={<FileText className="w-5 h-5" />}
          actions={
            <>
              <Select aria-label="Store" value={storeId ?? ''} onChange={(e) => setStoreId(e.target.value ? Number(e.target.value) : null)} className="!py-2.5 w-44">
                <option value="">All Stores</option>
                {stores.map((s) => <option key={s.id} value={s.id}>{s.name}</option>)}
              </Select>
              <Select aria-label="Period" value={range} onChange={(e) => setRange(e.target.value as ReportRange)} className="!py-2.5 w-40">
                <option value="7d">Last 7 Days</option>
                <option value="30d">Last 30 Days</option>
                <option value="90d">Last 90 Days</option>
              </Select>
              <Button variant="secondary" size="md" onClick={loadReport} aria-label="Refresh">
                <RefreshCw className={`w-4 h-4 ${loading ? 'animate-spin' : ''}`} />
              </Button>
              <Button variant="primary" size="md" onClick={handleExport} loading={exporting} disabled={!report}>
                {!exporting && <Download className="w-4 h-4" />}
                Export PDF
              </Button>
            </>
          }
        />

        {error && !loading ? (
          <Card variant="glass" padding="lg">
            <ErrorState
              title="Couldn't load the report"
              description="The sales report request failed. Check your connection and try again."
              onRetry={loadReport}
            />
          </Card>
        ) : (
          <Stagger>
            <RevealItem>
              <ReportKpiCards kpis={report?.kpis ?? null} loading={loading} />
            </RevealItem>

            <RevealItem className="block my-6">
              <ReportTrendPanel data={report?.daily_sales ?? []} loading={loading} />
            </RevealItem>

            <RevealItem className="grid grid-cols-1 lg:grid-cols-2 gap-6 mb-6">
              <ReportCategoryPanel data={report?.category_breakdown ?? []} loading={loading} />
              <ReportTopItemsPanel data={report?.top_items ?? []} loading={loading} />
            </RevealItem>

            <RevealItem>
              <ReportStoreTable data={report?.store_performance ?? []} loading={loading} />
            </RevealItem>
          </Stagger>
        )}
      </div>
    </main>
  );
}
