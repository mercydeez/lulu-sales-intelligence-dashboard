'use client';

import { useState, useEffect, useCallback } from 'react';
import { BarChart3, LineChart, RefreshCw, Download, Activity } from 'lucide-react';
import { useAuth } from '@/contexts/AuthContext';
import { PageHeader, Tabs, Button, Select } from '@/components/ui';
import {
  AnalyticsKpiCards,
  SalesTrendPanel,
  CategoryDonut,
  StoreDistributionPanel,
  TopItemsPanel,
  StorePerformanceTable,
  ForecastPanel,
  AnalyticsKpis,
  DateRange,
  RANGE_DAYS,
  formatCurrency,
} from '@/components/analytics';
import { fetchTrend, fetchCategoryBreakdown, clearCache } from '@/lib/api';
import { generatePDF } from '@/lib/pdfExport';
import { PRODUCT_NAME } from '@/lib/brand';

type Tab = 'overview' | 'forecast';

export default function AnalyticsPage() {
  const { user, authFetch, hasRole } = useAuth();
  const [activeTab, setActiveTab] = useState<Tab>('overview');
  const [range, setRange] = useState<DateRange>('30d');
  const [kpis, setKpis] = useState<AnalyticsKpis | null>(null);
  const [kpisLoading, setKpisLoading] = useState(true);
  const [refreshKey, setRefreshKey] = useState(0);
  const [exporting, setExporting] = useState(false);

  // Regional/super admins can compare across stores; store managers see only theirs.
  const showStoreComparison = hasRole(['super_admin', 'regional_manager']);
  const defaultStoreId = user?.accessible_stores?.[0] ?? 1;

  const loadKpis = useCallback(async () => {
    setKpisLoading(true);
    try {
      const res = await authFetch('/api/kpis');
      if (res.ok) setKpis(await res.json());
    } catch {
      // KPI cards fall back to em-dashes on failure.
    } finally {
      setKpisLoading(false);
    }
  }, [authFetch]);

  useEffect(() => {
    loadKpis();
  }, [loadKpis, refreshKey]);

  const handleRefresh = () => {
    clearCache();
    setRefreshKey((k) => k + 1);
  };

  const handleExport = async () => {
    setExporting(true);
    try {
      const [trend, categories] = await Promise.all([
        fetchTrend(RANGE_DAYS[range], false),
        fetchCategoryBreakdown(),
      ]);
      await generatePDF({
        title: 'Sales Analytics Report',
        subtitle: `${PRODUCT_NAME} — synthetic demo data`,
        dateRange: `Trend window: Last ${RANGE_DAYS[range]} days`,
        kpis: [
          { label: 'Revenue (7d)', value: formatCurrency(kpis?.total_revenue_week ?? 0) },
          { label: 'Revenue (30d)', value: formatCurrency(kpis?.total_revenue_month ?? 0) },
          { label: 'Avg Daily Revenue', value: formatCurrency(kpis?.average_daily_revenue ?? 0) },
          { label: 'Active Stores', value: kpis?.unique_stores ?? 0 },
        ],
        tables: [
          {
            title: 'Daily Revenue (historical)',
            data: {
              headers: ['Date', 'Revenue (AED)'],
              rows: trend.data
                .filter((d) => d.sales != null)
                .map((d) => [d.date, Math.round(d.sales ?? 0).toLocaleString()]),
            },
          },
          {
            title: 'Revenue by Category',
            data: {
              headers: ['Category', 'Revenue (AED)', 'Share'],
              rows: categories.data.map((c) => [
                c.category,
                Math.round(c.total_revenue).toLocaleString(),
                `${c.percentage.toFixed(1)}%`,
              ]),
            },
          },
        ],
        footer: `Figures are AED revenue (units × unit_price_aed). Generated by ${PRODUCT_NAME}.`,
      });
    } catch (err) {
      console.error('PDF export failed:', err);
    } finally {
      setExporting(false);
    }
  };

  return (
    <main className="min-h-screen p-4 md:p-8">
      <div className="max-w-7xl mx-auto">
        <PageHeader
          title="Analytics & Forecasting"
          description="Revenue trends, category and store breakdowns, and model-backed demand forecasts"
          icon={<BarChart3 className="w-5 h-5" />}
          actions={
            <>
              {activeTab === 'overview' && (
                <Select
                  aria-label="Trend window"
                  value={range}
                  onChange={(e) => setRange(e.target.value as DateRange)}
                  className="!py-2.5 w-40"
                >
                  <option value="7d">Last 7 Days</option>
                  <option value="30d">Last 30 Days</option>
                  <option value="90d">Last 90 Days</option>
                </Select>
              )}
              <Button variant="secondary" size="md" onClick={handleRefresh} aria-label="Refresh">
                <RefreshCw className="w-4 h-4" />
              </Button>
              <Button variant="primary" size="md" onClick={handleExport} loading={exporting}>
                {!exporting && <Download className="w-4 h-4" />}
                Export PDF
              </Button>
            </>
          }
        />

        <Tabs
          className="mb-6"
          value={activeTab}
          onChange={(id) => setActiveTab(id as Tab)}
          items={[
            { id: 'overview', label: 'Overview', icon: <Activity className="w-4 h-4" /> },
            { id: 'forecast', label: 'Forecast', icon: <LineChart className="w-4 h-4" /> },
          ]}
        />

        {activeTab === 'overview' ? (
          <div key={`overview-${refreshKey}`}>
            <AnalyticsKpiCards kpis={kpis} loading={kpisLoading} />

            <div className="mb-6">
              <SalesTrendPanel days={RANGE_DAYS[range]} />
            </div>

            <div className={`grid grid-cols-1 ${showStoreComparison ? 'lg:grid-cols-2' : ''} gap-6 mb-6`}>
              <CategoryDonut />
              {showStoreComparison && <StoreDistributionPanel />}
            </div>

            <div className="mb-6">
              <TopItemsPanel limit={10} />
            </div>

            <StorePerformanceTable />
          </div>
        ) : (
          <div key={`forecast-${refreshKey}`}>
            <ForecastPanel defaultStoreId={defaultStoreId} />
          </div>
        )}
      </div>
    </main>
  );
}
